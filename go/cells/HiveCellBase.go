// HiveCellBase implements the boilerplate of operating a cell.
// This implements the IHiveCell interface.
// - define and store properties
// - manage message sinks
// - generate TD
// - send notifications for property changes and events
// - control forwarding of requests and notifications
type HiveCellBase struct {

	// cellID is the instance ID of this cell. Used as the senderID in notifications
	// and in logging.
	cellID string

	// disable notification forwarding
	forwardNotifications atomic.Bool
	// enable request forwarding
	forwardRequests atomic.Bool

	// notificationSink is the sink for forwarding notification messages to registered cells.
	// sinks set with an empty thingID receive all notifications.
	// sinks set with a specific thingID will receive notifications for that thingID only.
	notificationSinks map[string]api.IHiveCell

	// mutex to access properties
	mux sync.RWMutex

	// requestSink is the cell to forward requests messages to
	requestSink api.IHiveCell

	rpcTimeout time.Duration
}

// EmitNotification passes emitted notifications to a registered sink.
//
// Use this for notifications generated by this cell.
// If no sinks are registered this does nothing.
func (base *HiveCellBase) EmitNotification(notif *msg.NotificationMessage) {
	base.mux.RLock()
	sink1, _ := base.notificationSinks[notif.ThingID]
	sink2, _ := base.notificationSinks[""]
	base.mux.RUnlock()

	// first notify the thingID registered cell
	if notif.ThingID != "" && sink1 != nil {
		sink1.HandleNotification(notif)
	}
	// next the generic sink
	if sink2 != nil {
		sink2.HandleNotification(notif)
	}
}

// EmitRequest sends a request to the sink's.
// If no sink os configured this returns an not-deliverable error
func (base *HiveCellBase) EmitRequest(req *msg.RequestMessage, replyTo msg.ResponseHandler) (err error) {
	if req.CorrelationID == "" {
		req.CorrelationID = shortid.MustGenerate()
	}
	base.mux.RLock()
	sink := base.requestSink
	base.mux.RUnlock()
	if sink == nil {
		return fmt.Errorf("EmitRequest: request '%s/%s' to thingID '%s' is undeliverable by cell '%s'",
			req.Operation, req.Name, req.ThingID, base.cellID)
	}
	if replyTo == nil {
		slog.Warn("EmitRequest: no replyTo handler provided",
			"cellID", base.cellID, "req.Sender", req.SenderID, "req.ThingID", req.ThingID)
	}
	err = sink.HandleRequest(req, replyTo)
	return err
}

// EmitRequestWait is a helper function to pass a request to the sink and wait for a response.
// If no sink os configured this returns an error.
// If the response contains an error, that error is also returned.
func (base *HiveCellBase) EmitRequestWait(req *msg.RequestMessage) (
	resp *msg.ResponseMessage, err error) {

	if req.CorrelationID == "" {
		req.CorrelationID = shortid.MustGenerate()
	}
	ar := utils.NewAsyncReceiver[*msg.ResponseMessage]()
	err = base.EmitRequest(req, func(r *msg.ResponseMessage) error {
		ar.SetResponse(r)
		return nil
	})
	if err != nil {
		return nil, err
	}
	timeout := base.rpcTimeout
	if timeout == 0 {
		timeout = msg.DefaultRnRTimeout
	}
	resp, err = ar.WaitForResponse(timeout)
	if err == nil {
		err = resp.AsError()
	} else {
		slog.Error("EmitRequestWait failed", "me", base.GetThingID(),
			"op", req.Operation,
			"thingID", req.ThingID,
			"name", req.Name, "err", err.Error())
	}
	return resp, err
}

// ForwardNotification passes received notifications to a registered sink.
//
// If forwarding is disables then this does nothing.
// Use this for notifications received on the HandleNotification interface.
// If no sinks are registered this does nothing.
func (base *HiveCellBase) ForwardNotification(notif *msg.NotificationMessage) {
	if base.forwardNotifications.Load() {
		base.mux.RLock()
		sink1, _ := base.notificationSinks[notif.ThingID]
		sink2, _ := base.notificationSinks[""]
		base.mux.RUnlock()

		// first notify the thingID registered cell
		if notif.ThingID != "" && sink1 != nil {
			sink1.HandleNotification(notif)
		}
		// next the generic sink
		if sink2 != nil {
			sink2.HandleNotification(notif)
		}
	}
}

// ForwardRequest passes the request to the sink's HandleRequest method.
// If no sink os configured this returns an not-deliverable error
func (base *HiveCellBase) ForwardRequest(req *msg.RequestMessage, replyTo msg.ResponseHandler) (err error) {
	if base.forwardRequests.Load() {
		base.mux.RLock()
		sink := base.requestSink
		base.mux.RUnlock()
		if sink == nil {
			// end of the line
			return fmt.Errorf("ForwardRequest: request '%s/%s' to thingID '%s' is undeliverable by cell '%s'",
				req.Operation, req.Name, req.ThingID, base.cellID)
		}
		if replyTo == nil {
			slog.Warn("ForwardRequest: no replyTo handler provided",
				"cellID", base.cellID, "req.Sender", req.SenderID, "req.ThingID", req.ThingID)
		}
		err = sink.HandleRequest(req, replyTo)
	}
	return err
}

// GetNotificationSink returns the default notification sink
// (the one without thingID)
func (base *HiveCellBase) GetNotificationSink() api.IHiveCell {
	base.mux.RLock()
	defer base.mux.RUnlock()
	sink, _ := base.notificationSinks[""]
	return sink
}

// GetRequestSink returns the cell's request sink
func (base *HiveCellBase) GetRequestSink() api.IHiveCell {
	base.mux.RLock()
	defer base.mux.RUnlock()
	return base.requestSink
}

// GetThingID returns the cell's thingID
func (base *HiveCellBase) GetThingID() string {
	return base.cellID
}

// GetTimeout returns the cell's rpc timeout
func (base *HiveCellBase) GetTimeout() time.Duration {
	return base.rpcTimeout
}

// HandleNotification receives an incoming notification from a producer.
//
// The default behavior is to forward the notification upstream to the notification sink,
// if enabled.
func (base *HiveCellBase) HandleNotification(notif *msg.NotificationMessage) {
	base.ForwardNotification(notif)
}

// HandleRequest handles request for this cell.
//
// This is just the default implementation that forwards the request downstream.
func (base *HiveCellBase) HandleRequest(req *msg.RequestMessage, replyTo msg.ResponseHandler) (err error) {
	return base.ForwardRequest(req, replyTo)
}

// Ready notifies the cell that the application environment is ready to go.
// Intended for cells to start autonomous operation, such as writing a TD, publishing
// events, properties.
//
// If Ready is not yet called, cells can already react to requests and emit requests
// and notifications in response, since these are only received after the environment
// is ready and cells are starting to receive the Ready call.
//
// By default this does nothing.
func (base *HiveCellBase) Ready() {
}

// Rpc is a convenience function to create and send a request message and decode the a response.
// This returns an error if the request fails or if the response contains an error
//
//	operation is the WoT operation to send, eg td.OpInvokeAction
//	thingID is the Thing to address
//	name is the operation name as defined in the TD
//	input are optional input parameters or nil if none
//	output is a pointer to the  struct where the result will be decoded
func (base *HiveCellBase) Rpc(
	operation, thingID, name string, input any, output any) error {

	var resp *msg.ResponseMessage
	req := msg.NewRequestMessage(operation, thingID, name, input)

	resp, err := base.EmitRequestWait(req)

	if err == nil && resp != nil {
		err = resp.Decode(output)
		if err != nil {
			err = fmt.Errorf("Rpc: Received response for op/thing/name '%s/%s/%s' but can't decode it: %w",
				operation, thingID, name, err)
		}
	}
	return err
}

